//  GENERIC / UNKNOWN
// ──────────────────────────
async fn generate_generic_template(config_dir: &Path, user: &str, name: &str) -> Result<()> {
    let desktop_dir = config_dir.join(format!("flake/users/{}/desktop", user));
    tokio::fs::create_dir_all(&desktop_dir).await?;

    let default_nix = format!(
        r##"# Desktop environment configuration for: {user}
# Custom/Unknown DE: {name}
{{ config, pkgs, lib, ... }}:

{{
  # Add your DE-specific configuration here.
  # See the NixOS Wiki for module options.
}}
"##,
        user = user,
        name = name
    );
    tokio::fs::write(desktop_dir.join("default.nix"), default_nix).await?;

    println!("✓ Generated minimal template for: {}", name);
    Ok(())
}
