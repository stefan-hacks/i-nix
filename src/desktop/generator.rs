//! Generate declarative Nix configurations for all supported DEs.
//!
//! Each DE has a dedicated function that writes a complete, ready-to-build
//! Home Manager + NixOS module set.

use anyhow::Result;
use colored::Colorize;
use std::path::Path;

use crate::desktop::detect::DesktopEnv;
use crate::desktop::gnome;

/// Generate a complete declarative configuration for a desktop environment.
pub async fn generate_de(
    de: &DesktopEnv,
    config_dir: &Path,
    user: &str,
    from_live: bool,
) -> Result<()> {
    match de {
        DesktopEnv::GNOME => {
            if from_live {
                gnome::generate_from_dconf(config_dir, user).await
            } else {
                generate_gnome_template(config_dir, user).await
            }
        }
        DesktopEnv::KDE => generate_kde(config_dir, user).await,
        DesktopEnv::Hyprland => generate_hyprland(config_dir, user).await,
        DesktopEnv::Sway => generate_sway(config_dir, user).await,
        DesktopEnv::i3 => generate_i3(config_dir, user).await,
        DesktopEnv::Niri => generate_niri(config_dir, user).await,
        DesktopEnv::Cinnamon => generate_cinnamon(config_dir, user).await,
        DesktopEnv::XFCE => generate_xfce(config_dir, user).await,
        DesktopEnv::PopOS => generate_popos(config_dir, user).await,
        DesktopEnv::QuickShell => generate_quickshell(config_dir, user).await,
        DesktopEnv::Noctalia => generate_noctalia(config_dir, user).await,
        DesktopEnv::DankLinux => generate_danklinux(config_dir, user).await,
        DesktopEnv::Unknown(s) => {
            println!(
                "{} Unknown desktop '{}'. Generating minimal template.",
                "⚠".yellow(),
                s
            );
            generate_generic_template(config_dir, user, s).await
        }
    }
}

// ──────────────────────────
//  GNOME (from template)
// ──────────────────────────
async fn generate_gnome_template(config_dir: &Path, user: &str) -> Result<()> {
    let desktop_dir = config_dir.join(format!("flake/users/{}/desktop", user));
    tokio::fs::create_dir_all(&desktop_dir).await?;

    let content = format!(
        r##"# Desktop environment configuration for: {user}
{{ config, pkgs, lib, ... }}:

{{
  imports = [ ./gnome-settings ];
}}
"##,
        user = user
    );
    tokio::fs::write(desktop_dir.join("default.nix"), content).await?;

    let settings_dir = desktop_dir.join("gnome-settings");
    tokio::fs::create_dir_all(&settings_dir).await?;

    // default.nix for gnome-settings
    let default = r##"# Generated by i-nix desktop generate gnome
# Do not hand-edit; re-run `i-nix desktop generate gnome` instead.

{ ... }:

{
  imports = [
    ./gtk.nix
    ./shell.nix
    ./shell-extensions.nix
  ];
}"##;
    tokio::fs::write(settings_dir.join("default.nix"), default).await?;

    // gtk.nix
    let gtk = r##"# Generated by i-nix desktop generate gnome
{ lib, ... }:

{
  dconf.settings = {
    "org/gnome/desktop/interface" = {
      clock-format = "24h";
      gtk-theme = "Adwaita";
      icon-theme = "Adwaita";
      cursor-theme = "Adwaita";
      enable-hot-corners = true;
    };
    "org/gnome/desktop/background" = {
      picture-uri = "file:///run/current-system/sw/share/backgrounds/gnome/vortex-gnome-l.jpg";
    };
  };
}"##;
    tokio::fs::write(settings_dir.join("gtk.nix"), gtk).await?;

    // shell.nix
    let shell = r##"# Generated by i-nix desktop generate gnome
{ lib, ... }:

{
  dconf.settings = {
    "org/gnome/shell" = {
      favorite-apps = [ "firefox.desktop" "org.gnome.Nautilus.desktop" "org.gnome.Console.desktop" ];
      disable-user-extensions = false;
    };
    "org/gnome/shell/keybindings" = {
      toggle-overview = [ "<Super>a" ];
    };
  };
}"##;
    tokio::fs::write(settings_dir.join("shell.nix"), shell).await?;

    // shell-extensions.nix
    let shell_ext = r##"# Generated by i-nix desktop generate gnome
{ lib, ... }:

{
  dconf.settings = {
    "org/gnome/shell/extensions/user-theme" = {
      name = "";
    };
  };
}"##;
    tokio::fs::write(settings_dir.join("shell-extensions.nix"), shell_ext).await?;

    println!();
    println!("✓ Generated GNOME declarative configuration");
    println!("  {} {}", "Directory:".dimmed(), settings_dir.display());
    println!();
    println!("  {}", "Run `i-nix desktop detect` then `i-nix apply`.".dimmed());
    println!();

    Ok(())
}

